/**
 * 获取任意历史人物的专属像素头像数据
 */
export function getPixelPortrait(
  figureId?: string,
  name?: string,
  camp: 'WEI' | 'SHU' | 'WU' | 'NEUTRAL' = 'NEUTRAL',
  archetype: string = 'MARTIAL'
): PixelPortraitData {
  if (figureId) {
    const canonicalId = FIGURE_ALIAS_MAP[figureId] || figureId;
    if (PIXEL_FIGURES_MAP[canonicalId]) {
      return PIXEL_FIGURES_MAP[canonicalId];
    }
  }

  // 尝试根据名字匹配
  if (name) {
    for (const key of Object.keys(PIXEL_FIGURES_MAP)) {
      const data = PIXEL_FIGURES_MAP[key];
      if (data.name === name || name.includes(data.name) || data.name.includes(name)) {
        return data;
      }
    }
  }

  // Fallback 到对应原型的像素头像
  return getGenericArchetypePixelPortrait(archetype, camp, name || '名士');
}
